export function catalogEntry(id: string): CatalogEntry | undefined {
  return CATALOG.find((c) => c.id === id);
}

/** Build a server config from a catalog entry and user inputs. Secrets become ${secret:KEY} references. */
export function buildCatalogConfig(entry: CatalogEntry, inputs: Record<string, string>): { config: McpServerConfig; secrets: Record<string, string> } {
  const secrets: Record<string, string> = {};
  const values: Record<string, string> = {};
  for (const inp of entry.inputs ?? []) {
    const v = (inputs[inp.key] ?? inp.default ?? '').trim();
    if (!v && !inp.optional) throw new Error(`"${inp.label}" is required`);
    if (inp.secret && v) {
      secrets[inp.key] = v;
      values[inp.key] = `\${secret:${inp.key}}`;
    } else values[inp.key] = v;
  }
  const fill = (s: string) => s.replace(/\{\{(\w+)\}\}/g, (_, k) => values[k] ?? '');
  const c = entry.config;
  const config: McpServerConfig = {
    ...c,
    args: c.args?.map(fill),
    url: c.url ? fill(c.url) : undefined,
    env: c.env ? Object.fromEntries(Object.entries(c.env).map(([k, v]) => [k, fill(v)])) : undefined,
    headers: c.headers ? Object.fromEntries(Object.entries(c.headers).map(([k, v]) => [k, fill(v)]).filter(([, v]) => v && !/^Bearer\s*$/.test(v))) : undefined,
    catalogId: entry.id,
  };
  for (const k of Object.keys(config) as (keyof McpServerConfig)[]) if (config[k] === undefined) delete config[k];
  return { config, secrets };
}
