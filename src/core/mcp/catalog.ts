import type { McpServerConfig } from '../types.js';

/**
 * Curated integrations. Each entry installs an MCP server configuration.
 * Inputs marked `secret` are stored in ~/.drakox/credentials.json (0600), never in config files;
 * the config references them as ${secret:NAME}. Anything not listed here can be added from the
 * official MCP Registry search or as a custom server (stdio / HTTP / SSE).
 */
export interface CatalogInput {
  key: string;
  label: string;
  secret?: boolean;
  placeholder?: string;
  help?: string;
  optional?: boolean;
  default?: string;
}

export type CatalogCategory =
  | 'Dev & Code'
  | 'Browser & Web'
  | 'Productivity'
  | 'Data & Databases'
  | 'Cloud & Deploy'
  | 'Design'
  | 'Payments & Business'
  | 'Automation hubs'
  | 'AI & Knowledge'
  | 'Reverse engineering';

export interface CatalogEntry {
  id: string;
  name: string;
  category: CatalogCategory;
  description: string;
  /** Brand color for the UI tile */
  color: string;
  /** Short monogram/emoji for the tile */
  icon: string;
  publisher: string;
  official?: boolean;
  auth: 'none' | 'token' | 'oauth' | 'local-app';
  homepage?: string;
  inputs?: CatalogInput[];
  /** Config template; `{{key}}` is replaced by plain inputs, secrets become ${secret:key} */
  config: McpServerConfig;
  /** Requirements shown to the user */
  requires?: string;
  featured?: boolean;
}

const npx = (...args: string[]): McpServerConfig => ({ type: 'stdio', command: 'npx', args: ['-y', ...args] });
const uvx = (...args: string[]): McpServerConfig => ({ type: 'stdio', command: 'uvx', args });

